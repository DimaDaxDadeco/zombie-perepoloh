// Приведение текста к тому виду, в котором его произносят.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Одну и ту же фразу произносят два разных механизма:
// заранее записанный файл (его делает tools/voice-build.mjs) и синтез речи в
// браузере. Ключ в манифесте банка — это САМ ТЕКСТ, поэтому нормализация
// обязана быть одной и той же функцией по обе стороны: разойдись они на один
// пробел, и рантайм перестанет находить готовые файлы, молча свалившись на
// робота.
//
// Функция чистая и без побочных эффектов: её импортируют и браузер, и Node.

// Разметка в озвучке — не гипотетическая беда. describeAbility подставлял в
// фразу результат icon(), то есть целую строку SVG, и ребёнок, нажав динамик
// на герое, слушал разметку. Источник поправлен, но сетка нужна: ошибка
// повторится, и заметить её на слух почти невозможно.
const TAGS = /<[^>]*>/g;

const ENTITIES = {
  '&amp;': 'и', '&quot;': '', '&#39;': '', '&apos;': '', '&lt;': '', '&gt;': '', '&nbsp;': ' ',
};

// Символы, которые синтез читает как попало либо не читает вовсе. В CONFIG их
// сегодня нет — это профилактика, и парсером она становиться не должна.
const SIGNS = [
  [/\s*[×x]\s*(?=\d)/gi, ' на '],
  [/\s*\+\s*/g, ' плюс '],
  [/\s*%\s*/g, ' процентов '],
  [/\s*=\s*/g, ' равно '],
  [/(\d)\s*\/\s*(\d)/g, '$1 из $2'],
];

// Латиница: Milena читает её по буквам с русским акцентом, и ребёнок слышит
// шум. Карта явная — тест предупредит про любой латинский прогон вне неё.
const LATIN = [
  [/\bHP\b/g, 'здоровье'],
  [/\bXP\b/g, 'опыт'],
  [/\bWASD\b/g, 'вэ, а, эс, дэ'],
];

const UNITS = ['ноль', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];
const UNITS_F = ['ноль', 'одна', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];
const TEENS = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать',
  'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать'];
const TENS = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят',
  'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто'];
const HUNDREDS = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот',
  'шестьсот', 'семьсот', 'восемьсот', 'девятьсот'];

// Род определяется по существительному ПОСЛЕ числа, и только по знакомому:
// «одна звезда» и «один доллар» отличаются, а угадывать род по окончанию
// нельзя — неправильное согласование ребёнок замечает сразу и переспрашивает.
// Незнакомое слово оставляет цифру цифрой: синтез прочтёт её сам, и это
// заведомо безопаснее нашей догадки.
const NOUN_GENDER = [
  [/^звезд|^звёзд/i, 'f'],
  [/^медал/i, 'f'],
  [/^жизн/i, 'f'],
  [/^глав/i, 'f'],
  [/^доллар/i, 'm'],
  [/^зомби/i, 'm'],
  [/^сердечк/i, 'n'],
];

function numeral(value, gender) {
  if (value < 0 || value > 999) return null;
  const parts = [];
  const hundreds = Math.floor(value / 100);
  if (hundreds) parts.push(HUNDREDS[hundreds]);
  const rest = value % 100;
  if (rest >= 10 && rest < 20) {
    parts.push(TEENS[rest - 10]);
  } else {
    const tens = Math.floor(rest / 10);
    if (tens) parts.push(TENS[tens]);
    const unit = rest % 10;
    // Ноль произносится только сам по себе: «сто ноль» — это не число.
    if (unit || (!parts.length && !unit)) {
      parts.push(gender === 'f' ? UNITS_F[unit] : UNITS[unit]);
    }
  }
  return parts.join(' ');
}

function spellNumbers(text) {
  return text.replace(/(\d{1,3})(\s+)([А-Яа-яЁё]+)/g, (whole, digits, gap, word) => {
    const rule = NOUN_GENDER.find(([re]) => re.test(word));
    if (!rule) return whole;
    const words = numeral(Number(digits), rule[1]);
    return words === null ? whole : `${words}${gap}${word}`;
  });
}

export function normalizeVoice(text) {
  if (!text) return '';
  let out = String(text).replace(TAGS, ' ');
  for (const [entity, value] of Object.entries(ENTITIES)) out = out.split(entity).join(value);
  out = spellNumbers(out);
  for (const [re, value] of SIGNS) out = out.replace(re, value);
  for (const [re, value] of LATIN) out = out.replace(re, value);
  // Тире синтезу не говорит ничего, а запятая даёт настоящую паузу.
  out = out.replace(/\s*[—–]\s*/g, ', ');
  // Для say текст в двойных квадратных скобках — встроенная команда движка.
  out = out.replace(/\[+/g, ' ').replace(/\]+/g, ' ');
  out = out.replace(/([!?.,:;])\1+/g, '$1');
  return out.replace(/\s+/g, ' ').replace(/\s+([!?.,:;])/g, '$1').trim();
}
