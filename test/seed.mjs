// Детерминизм прогонов: подменяемый Math.random.
//
// Зачем. Игра случайна насквозь — спавн, лут, разброс карточек, — и замер
// баланса поэтому шумел на ±7 побед из 90. В balance.md записано следствие:
// героя и эталон приходилось мерить в ОДНОМ прогоне, иначе сравнение обманет.
// С сеемым генератором прогон повторяется побитово, и эффект правки конфига
// становится виден точно, а не «где-то в пределах шума».
//
// Подменять надо ДО первого импорта игрового кода — на случай, если модуль
// когда-нибудь возьмёт Math.random на верхнем уровне. Отсюда правило: файлы
// теста импортируют игру динамическим import() после вызова seedRandom.
//
// В самой игре ничего для этого править не пришлось и не надо: подмена живёт
// только здесь.

// mulberry32 — минимальный PRNG на 32 битах состояния. Криптостойкость тут не
// нужна вовсе, нужна воспроизводимость.
function mulberry32(seed) {
  let a = seed;
  return function random() {
    a |= 0;
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const nativeRandom = Math.random;

export function seedRandom(seed) {
  Math.random = mulberry32(seed);
}

// Вернуть настоящий генератор. Нужен, чтобы забытая подмена не утекла в
// соседний прогон и не сделала два разных теста одинаковыми.
export function unseedRandom() {
  Math.random = nativeRandom;
}

// Прогнать функцию на фиксированном сиде и убрать за собой в любом случае.
export function withSeed(seed, fn) {
  seedRandom(seed);
  try {
    return fn();
  } finally {
    unseedRandom();
  }
}
